import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { root } from "./lib.mjs";

const contract = JSON.parse(
	readFileSync(
		join(root, "tests", "parity", "fixtures", "contract.json"),
		"utf8",
	),
);

const tools = contract.mcp.tools.tools;
const entries = tools
	.map(
		(tool) =>
			`    (${JSON.stringify(tool.name)}, ${JSON.stringify(
				JSON.stringify(tool.inputSchema),
			)}, ${JSON.stringify(JSON.stringify(tool.outputSchema ?? null))}),`,
	)
	.join("\n");

const operations = contract.ops.map(
	(op) =>
		`    (${JSON.stringify(op.name)}, ${JSON.stringify(
			JSON.stringify(op.input),
		)}, ${JSON.stringify(JSON.stringify(op.output ?? null))}),`,
);

const schemas = `pub const TOOLS: [(&str, &str, &str); ${tools.length}] = [
${entries}
];

pub const OPERATIONS: [(&str, &str, &str); ${operations.length}] = [
${operations.join("\n")}
];
`;

const read = tools.find((tool) => tool.name === "attachments_read");
const [fixed, ...files] = contract.mcp.resources.resources;
const template = contract.mcp.templates.resourceTemplates[0];
const lines = [
	"pub const INSTRUCTIONS: &str = " +
		JSON.stringify(contract.mcp.initialize.instructions) +
		";",
	"",
	"pub const ATTACHMENTS_READ_DESCRIPTION: &str = " +
		JSON.stringify(read.description) +
		";",
	"",
	"pub const RESOURCES_DESCRIPTION: &str = " +
		JSON.stringify(fixed.description) +
		";",
	"",
	"pub const RESOURCES_TITLE: &str = " + JSON.stringify(fixed.title) + ";",
	"",
	"pub const TEMPLATE_TITLE: &str = " + JSON.stringify(template.title) + ";",
	"",
	"pub const TEMPLATE_DESCRIPTION: &str = " +
		JSON.stringify(template.description) +
		";",
	"",
	"pub const ATTACHMENT_TITLE: &str = " + JSON.stringify(files[0].title) + ";",
];

writeFileSync(join(root, "crates", "ops", "src", "schemas.rs"), schemas);
writeFileSync(
	join(root, "crates", "server", "src", "mcp_text.rs"),
	`// NOTE: generated by scripts/parity/schemas.mjs from the node snapshot\n${lines.join("\n")}\n`,
);
console.log(`wrote ${tools.length} tool schemas and the mcp texts`);
